vtkEyeBallSource::vtkEyeBallSource()
{
  this->Center[0] = 0.0;
  this->Center[1] = 0.0;
  this->Center[2] = 0.0;
  this->Normal[0] = 0.0;
  this->Normal[1] = 0.0;
  this->Normal[2] = 1.0;
  this->Direction[0] = 0.0;
  this->Direction[1] = 1.0;
  this->Direction[2] = 0.0;
  this->Scale = 1.0;
  this->GeneratePolyline = true;
  this->GeneratePolygon = true;
  this->SetNumberOfInputPorts(0);
}

void vtkEyeBallSource::PrintSelf(ostream& os, vtkIndent indent)
{
  this->Superclass::PrintSelf(os, indent);
  os << indent << "Center: (" << this->Center[0] << ", " << this->Center[1] << ", " << this->Center[2] << ")\n";
  os << indent << "Normal: (" << this->Normal[0] << ", " << this->Normal[1] << ", " << this->Normal[2] << ")\n";
  os << indent << "Direction: (" << this->Direction[0] << ", " << this->Direction[1] << ", " << this->Direction[2] << ")\n";
  os << indent << "Scale: " << this->Scale << "\n";
  os << indent << "GeneratePolyline: " << (this->GeneratePolyline ? "on" : "off") << "\n";
  os << indent << "GeneratePolygon: " << (this->GeneratePolygon ? "on" : "off") << "\n";
}

int vtkEyeBallSource::RequestData(
  vtkInformation*,
  vtkInformationVector**,
  vtkInformationVector* outputVector)
{
  vtkPolyData* output = vtkPolyData::GetData(outputVector, 0);

  double nrm[3] = { this->Normal[0], this->Normal[1], this->Normal[2] };
  double len = vtkMath::Normalize(nrm);
  if (len < 1e-15)
  {
    vtkErrorMacro("Normal vector must be non-zero and have non-negligible length.");
    return 0;
  }

  double d[3] = { this->Direction[0], this->Direction[1], this->Direction[2] };
  if (vtkMath::Norm(d) < 1e-15)
  {
    vtkErrorMacro("Direction vector must be non-zero.");
    return 0;
  }
  const double dot = vtkMath::Dot(d, nrm);
  d[0] -= dot * nrm[0];
  d[1] -= dot * nrm[1];
  d[2] -= dot * nrm[2];
  len = vtkMath::Normalize(d);
  if (len < 1e-15)
  {
    vtkErrorMacro("Direction vector must not be parallel to Normal.");
    return 0;
  }
  const double ay[3] = { d[0], d[1], d[2] };

  double ax[3];
  vtkMath::Cross(ay, nrm, ax);

  int totalPts = 0;
  for (int ci = 0; ci < ContourCount; ++ci)
  {
    totalPts += ContourPointCounts[ci];
  }

  vtkNew<vtkPoints> pts;
  pts->SetDataTypeToDouble();
  pts->Allocate(totalPts);

  vtkNew<vtkCellArray> polys;
  vtkNew<vtkCellArray> lines;

  int offset = 0;
  for (int ci = 0; ci < ContourCount; ++ci)
  {
    const int nPts = ContourPointCounts[ci];
    const vtkIdType startId = pts->GetNumberOfPoints();

    for (int pi = 0; pi < nPts; ++pi)
    {
      const double u = ContourPoints[offset + pi][0] * this->Scale;
      const double v = ContourPoints[offset + pi][1] * this->Scale;
      pts->InsertNextPoint(
        this->Center[0] + u * ax[0] + v * ay[0],
        this->Center[1] + u * ax[1] + v * ay[1],
        this->Center[2] + u * ax[2] + v * ay[2]);
    }

    if (this->GeneratePolygon)
    {
      polys->InsertNextCell(nPts);
      for (int pi = 0; pi < nPts; ++pi)
      {
        polys->InsertCellPoint(startId + pi);
      }
    }

    if (this->GeneratePolyline)
    {
      lines->InsertNextCell(nPts + 1);
      for (int pi = 0; pi < nPts; ++pi)
      {
        lines->InsertCellPoint(startId + pi);
      }
      lines->InsertCellPoint(startId);
    }

    offset += nPts;
  }

  if (this->GeneratePolygon)
  {
    vtkNew<vtkPolyData> tempPd;
    tempPd->SetPoints(pts);
    tempPd->SetPolys(polys);
    if (this->GeneratePolyline)
    {
      tempPd->SetLines(lines);
    }

    vtkNew<vtkTriangleFilter> triFilter;
    triFilter->SetInputData(tempPd);
    triFilter->PassVertsOff();
    triFilter->PassLinesOn();
    triFilter->Update();

    output->ShallowCopy(triFilter->GetOutput());
  }
  else
  {
    output->SetPoints(pts);
    if (this->GeneratePolyline)
    {
      output->SetLines(lines);
    }
  }

  return 1;
}
